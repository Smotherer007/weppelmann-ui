; Sprechwerk — zwei Sprechblasen, türkis hinten, orange vorne.
;
; Die Fläche ist dunkel (neutral.900), die Zeichnung türkis, der Schatten
; orange. Das weicht von der Regel „Fläche bunt, Zeichnung Knochenweiß" ab;
; die Begründung steht in sprechwerk/docs/adr/0014-marke-zwei-farben.md.
;
; Was die Form bestimmt (überarbeitet am 2026-11-22, siehe PR):
; * Ecken als Pixel-Treppe mit 2-px-Stufen. Ein hartes Rechteck liest als
;   Fenster, nicht als Blase; eine glatte Rundung gibt es im Raster nicht.
; * Die Balken sind eine Audio-Wellenform: symmetrisch, Mitte hoch, außen
;   niedrig (2-4-6-4-2 hinten, 2-6-2 vorne). Eine ansteigende Treppe sähe aus
;   wie ein Balkendiagramm; außen kurz, innen lang heißt: hier läuft ein Pegel.
; * Luft: mindestens 1 px zwischen Balken und Umriss, damit die Balken nicht
;   mit der Blase verkleben.
; * Zwei Blasen: die orange ist etwa 70 % der türkisen breit, überdeckt deren
;   untere rechte Ecke und hat einen eigenen Schwanz unten rechts. Zwischen
;   beiden liegt 1 px Fläche — sonst verschmelzen sie bei 16 px zu einem Fleck.
; * Alles liegt auf 2-px-Raster und 2-px-Strich, die Umrisse beginnen auf
;   geraden Koordinaten: verkleinert wird mit Mehrheitsentscheid, und was auf
;   halben Pixeln sitzt, fällt bei 16 px weg.
;
; Abstand: mindestens 1 px zur Kante und zur Fase des Achtecks.

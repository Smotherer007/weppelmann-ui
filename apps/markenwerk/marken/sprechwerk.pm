; Sprechwerk — zwei Sprechblasen, türkis hinten, orange vorne.
;
; Die Fläche ist dunkel (neutral.900), die Zeichnung türkis, der Schatten
; orange. Das weicht von der Regel „Fläche bunt, Zeichnung Knochenweiß" ab;
; die Begründung steht in sprechwerk/docs/adr/0014-marke-zwei-farben.md.
;
; Vorlage ist der Entwurf des Nutzers (sprechwerk/docs/marke/entwurf.png).
; Was die Form bestimmt:
; * Beide Blasen sind geschlossene Ringe von 2 Zellen Dicke — rundum, auch
;   unten. Ein offener Umriss liest bei 16 px als Bruchstück.
; * Ecken sind 45-Grad-Treppen mit 1-Zellen-Stufen, keine glatte Rundung: die
;   gibt es im Raster nicht, und eine harte Rechteckecke liest als Fenster.
;   Vorne links lang (5 Stufen), damit sich die orange Blase in die untere
;   rechte Ecke der türkisen legt; sonst kurz (2-3 Stufen).
; * Der Schwanz ist eine Zacke aus 4 Zeilen, die je Zeile um eine Zelle nach außen
;   wandert (türkis nach unten links, orange nach unten rechts).
; * Die Balken sind eine Welle: symmetrisch, Mitte lang, außen kurz
;   (3-5-8-5-3 hinten, 2-4-6-4-2 vorne). Eine ansteigende Treppe sähe aus wie
;   ein Balkendiagramm; außen kurz, innen lang heißt: hier läuft ein Pegel.
; * Die Balken stehen auf ungeraden Spalten und sind eine Zelle breit. Beim
;   Verkleinern auf 16 px deckt ein Balken dann genau die Hälfte eines
;   Zielpixels — die Mehrheitsentscheidung wirft ihn weg, und es bleibt die
;   Blase. Deshalb braucht das 16er keine eigene Fassung.
; * Alle Ringe beginnen auf geraden Koordinaten. 32 → 16 ist glatt halbiert;
;   was auf halben Pixeln sitzt, verschwindet dort (2 von 4 = keine Mehrheit).
; * Die orange Blase ist deckend: sie löscht die türkise, wo sie davor liegt.
;
; Abstand: mindestens 1 px zur Kante und zur Fase des Achtecks.
